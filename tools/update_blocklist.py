#!/usr/bin/env python3
"""Download the StevenBlack hosts list and generate ../blocklist_data.h.

The header holds the domains sorted in strcmp() order, so the firmware can
binary-search them in place in flash. Re-run this and re-upload the sketch to
refresh the list.

Usage:
  tools/update_blocklist.py              # download from the default URL
  tools/update_blocklist.py hosts.txt    # use a local hosts file instead
"""
import datetime
import os
import re
import sys
import urllib.request

URL = "https://raw.githubusercontent.com/StevenBlack/hosts/master/hosts"
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "blocklist_data.h")
VALID = re.compile(r"^[a-z0-9._-]+$")
MAX_LEN = 253


def parse(text):
    domains = set()
    for line in text.splitlines():
        line = line.split("#", 1)[0].split()
        if len(line) < 2 or line[0] not in ("0.0.0.0", "127.0.0.1"):
            continue
        for name in line[1:]:
            name = name.lower().rstrip(".")
            if (name and len(name) <= MAX_LEN and "." in name
                    and name != "0.0.0.0" and VALID.match(name)):
                domains.add(name)
    # Byte-wise order == strcmp() order for ASCII.
    return sorted(domains, key=lambda s: s.encode())


def main():
    if len(sys.argv) > 1:
        source = sys.argv[1]
        with open(source, encoding="utf-8", errors="replace") as f:
            text = f.read()
    else:
        source = URL
        print(f"downloading {URL}")
        with urllib.request.urlopen(URL, timeout=60) as r:
            text = r.read().decode("utf-8", errors="replace")

    domains = parse(text)
    if len(domains) < 1000:
        sys.exit(f"only {len(domains)} domains found, refusing to write")

    offsets, pos = [], 0
    for d in domains:
        offsets.append(pos)
        pos += len(d) + 1

    stamp = datetime.datetime.now(datetime.timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
    with open(OUT, "w", encoding="ascii", newline="\n") as f:
        f.write("// Generated by tools/update_blocklist.py - do not edit.\n")
        f.write(f"// Source:  {source}\n// Created: {stamp}\n")
        f.write(f"// Domains: {len(domains)}, string data {pos} bytes\n")
        f.write("#pragma once\n#include <stdint.h>\n\n")
        f.write(f'#define BLOCKLIST_SOURCE "{source}"\n')
        f.write(f'#define BLOCKLIST_CREATED "{stamp}"\n')
        f.write(f"static const uint32_t BLOCKLIST_COUNT = {len(domains)};\n\n")
        f.write("// Offset of each domain in BLOCKLIST_STRINGS, sorted.\n")
        f.write(f"static const uint32_t BLOCKLIST_INDEX[{len(domains)}] = {{\n")
        for i in range(0, len(offsets), 12):
            f.write("  " + ",".join(str(o) for o in offsets[i:i + 12]) + ",\n")
        f.write("};\n\n")
        f.write("// NUL-separated domains. Each one is its own literal, so a \\0 is\n")
        f.write("// never followed by a digit inside a literal (no octal escapes).\n")
        f.write(f"static const char BLOCKLIST_STRINGS[] =\n")
        for d in domains:
            f.write(f'  "{d}\\0"\n')
        f.write(";\n")
    print(f"wrote {os.path.normpath(OUT)}: {len(domains)} domains, {pos} bytes of strings")


if __name__ == "__main__":
    main()
